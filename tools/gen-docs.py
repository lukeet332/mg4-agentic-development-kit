#!/usr/bin/env python3
"""Regenerate docs/API.md from the app's own OpenAPI document.

The docs are a view of the contract, not a second copy of it: point this at a
running car (or a saved spec) and the reference is rebuilt from what the app
actually serves, so it cannot drift.

    tools/gen-docs.py                                  # http://127.0.0.1:8787
    tools/gen-docs.py --url http://192.168.1.50:8787 --token ...
    tools/gen-docs.py --spec-file /tmp/openapi.json     # offline
"""
import argparse
import json
import os
import sys
import urllib.request

TYPE_LABEL = {
    "string": "string", "integer": "int", "number": "number",
    "boolean": "bool", "object": "json", "array": "list",
}


def fetch(url, token, spec_file):
    if spec_file:
        with open(spec_file) as fh:
            return json.load(fh)
    req = urllib.request.Request(url.rstrip("/") + "/openapi.json")
    if token:
        req.add_header("X-ADK-Token", token)
    with urllib.request.urlopen(req, timeout=30) as resp:
        return json.loads(resp.read().decode("utf-8"))


def render(spec, source):
    info = spec.get("info") or {}
    lines = [
        "# ADK API reference",
        "",
        f"Generated by `tools/gen-docs.py` from `{source}` — **do not edit by hand**.",
        "",
        f"*{info.get('description', '')}*",
        "",
        f"- Title: **{info.get('title', 'Agentic Development Kit')}**",
        f"- Version: `{info.get('version', '?')}`",
        f"- Spec revision: `{spec.get('x-adk-spec-version', '?')}`",
        f"- Endpoints: **{sum(len([m for m in item if m in ('get','post','put','delete','patch')]) for item in (spec.get('paths') or {}).values())}**",
        "",
        "Authentication: `X-ADK-Token: <token>` (also `Authorization: Bearer <token>` or `?token=`).",
        "Endpoints marked *no token* are the only unauthenticated ones.",
        "Pairing: `POST /pair` with the 6-digit code from the car app.",
        "",
        "## Index",
        "",
        "| Operation | Method | Path | Auth | Returns |",
        "| --- | --- | --- | --- | --- |",
    ]
    rows = []
    for path, item in sorted((spec.get("paths") or {}).items()):
        for method, op in sorted(item.items()):
            if method not in ("get", "post", "put", "delete", "patch"):
                continue
            rows.append((op.get("operationId", ""), method.upper(), path, op))
            auth = "no token" if op.get("x-adk-auth") == "no" else "token"
            lines.append(f"| `{op.get('operationId','')}` | `{method.upper()}` | `{path}` | {auth} "
                         f"| `{op.get('x-adk-returns','json')}` |")
    lines += ["", "## Endpoints", ""]

    for op_id, method, path, op in rows:
        auth = "no token" if op.get("x-adk-auth") == "no" else "token required"
        lines += [
            f"### `{op_id}`",
            "",
            f"**{method} {path}** — {op.get('summary','')}",
            "",
            f"- Auth: {auth}",
            f"- Returns: `{op.get('x-adk-returns','json')}`",
        ]
        if op.get("x-adk-example"):
            lines.append(f"- Example: `{op['x-adk-example']}`")

        params = op.get("parameters") or []
        body_schema = (((op.get("requestBody") or {}).get("content") or {})
                       .get("application/json") or {}).get("schema") or {}
        body_props = body_schema.get("properties") or {}
        body_required = set(body_schema.get("required") or [])
        raw_body = "application/octet-stream" in ((op.get("requestBody") or {}).get("content") or {})

        if params or body_props or raw_body:
            lines += ["", "| Param | In | Type | Required | Default | Notes |",
                      "| --- | --- | --- | --- | --- | --- |"]
            for p in params:
                schema = p.get("schema") or {}
                lines.append("| `{}` | query | {} | {} | {} | {} |".format(
                    p.get("name"), TYPE_LABEL.get(schema.get("type"), schema.get("type", "?")),
                    "yes" if p.get("required") else "no",
                    f"`{schema['default']}`" if "default" in schema else "—",
                    (p.get("description") or "").replace("|", "\\|")))
            for name, schema in body_props.items():
                lines.append("| `{}` | body | {} | {} | {} | {} |".format(
                    name, TYPE_LABEL.get(schema.get("type"), schema.get("type", "?")),
                    "yes" if name in body_required else "no",
                    f"`{schema['default']}`" if "default" in schema else "—",
                    (schema.get("description") or "").replace("|", "\\|")))
            if raw_body:
                desc = ((op.get("requestBody") or {}).get("description") or "raw request body")
                lines.append(f"| *(raw body)* | body | bytes | yes | — | {desc.replace('|', chr(92)+'|')} |")
        lines.append("")

    lines += [
        "## See also",
        "",
        "- [AGENT.md](AGENT.md) — how an agent should drive the car",
        "- `GET /help` — the same information as JSON at runtime",
        "- `GET /` — human dashboard",
        "",
    ]
    return "\n".join(lines)


def main():
    ap = argparse.ArgumentParser(description=__doc__,
                                 formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("--url", default=os.environ.get("ADK_URL", "http://127.0.0.1:8787"))
    ap.add_argument("--token", default=os.environ.get("ADK_TOKEN", ""))
    ap.add_argument("--spec-file", help="read a saved openapi.json instead of the car")
    ap.add_argument("--out", default=os.path.join(os.path.dirname(os.path.abspath(__file__)),
                                                  "..", "docs", "API.md"))
    args = ap.parse_args()
    source = args.spec_file or f"{args.url.rstrip('/')}/openapi.json"
    try:
        spec = fetch(args.url, args.token, args.spec_file)
    except Exception as e:
        print(f"cannot read the spec from {source}: {e}", file=sys.stderr)
        return 1
    out = os.path.abspath(args.out)
    os.makedirs(os.path.dirname(out), exist_ok=True)
    with open(out, "w") as fh:
        fh.write(render(spec, source))
    print(f"wrote {out} ({len(spec.get('paths') or {})} paths)")
    return 0


if __name__ == "__main__":
    sys.exit(main())
